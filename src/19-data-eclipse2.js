/* 相容性：只判斷「這台車能不能裝」，不做 E36 那套輪圈幾何計算 */
function eclCompat(p, c){
  const m = mdlById(c && c.modelId), eng = carEngine(c);
  const f = p.fit || {};
  const R = [];
  let lv = 'g';
  if(f.turbo){
    if(eng && eng.id==='4G63T') R.push({k:'g', t:'這台是 4G63 渦輪車，符合這個零件的前提'});
    else { lv='r'; R.push({k:'r', t:'這個零件只適用渦輪車型（GS-T／GSX／Spyder GS-T）。420A 自然進氣的 RS／GS 裝不上'}); }
  }
  if(f.awd){
    if(m && m.drive==='AWD') R.push({k:'g', t:'這台是 AWD 的 GSX，符合'});
    else { lv='r'; R.push({k:'r', t:'這是 AWD 專屬零件，只有 GSX 有'}); }
  }
  if(!f.turbo && !f.awd) R.push({k:'g', t:'2G Eclipse 全車系適用'});
  if(p.stage>=3 && lv==='g'){ lv='y'; R.push({k:'y', t:'這是重度改裝項目，需要同步升級供油、電腦與傳動，不能單獨裝'}); }
  if(p.impact && p.impact.legal && p.impact.legal.length) R.push({k:'y', t:p.impact.legal[0]});
  return {lv, R};
}
